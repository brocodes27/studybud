/**
 * Generates NCERT-based, personalized flashcards using RAG
 * with hierarchical performance logic.
 */
async function generateFlashcards(auth_user_id, requestBody) {
    const { subject, topic } = requestBody;

    if (!subject || !topic) {
        throw new Error("Missing 'subject' or 'topic' in request body.");
    }

    // --- 1. RETRIEVAL ---
    const userData = await getUserData(auth_user_id);
    const { class: userClass, performance_summary } = userData;

    // --- 2. AUGMENTATION (with new hierarchical logic) ---
    let performanceProfile = "No specific performance data available.";
    let difficultyRequest = "a standard mix of foundational and application questions";

    try {
        const subjectData = performance_summary?.by_subject?.[subject];
        const chapterData = subjectData?.by_chapter?.[topic];

        // Helper function to parse performance numbers
        const getNum = (field) => parseFloat(field?.$numberDouble || field || 0);

        if (chapterData) {
            // RULE 1: Use specific chapter/topic data
            const chapterStrength = chapterData.strength_level || 'moderate';
            const chapterAccuracy = (getNum(chapterData.accuracy) * 100).toFixed(0);
            
            performanceProfile = `Student has specific data for this topic: **Strength: ${chapterStrength}**, **Accuracy: ${chapterAccuracy}%**.`;

            if (chapterStrength === 'weak') {
                difficultyRequest = "focus heavily on **basic-intermediate definitions and foundational formulas**. The student is weak in this specific topic.";
            } else if (chapterStrength === 'strong') {
                difficultyRequest = "focus on **difficult, complex, and multi-step application-based questions**. The student is strong in this topic.";
            } else { // moderate
                difficultyRequest = "a mix of foundational concepts and moderately complex application problems. The student has moderate strength here.";
            }

        } else if (subjectData) {
            // RULE 2: No topic data, use subject data
            const subjectStrength = subjectData.strength_level || 'moderate';
            
            performanceProfile = `No data for this specific topic. Using overall **${subject}** subject data: **Strength: ${subjectStrength}**.`;

            if (subjectStrength === 'weak') {
                difficultyRequest = "focus on **basic-intermediate concepts** for this topic, as the student is generally weak in ${subject}.";
            } else if (subjectStrength === 'strong') {
                difficultyRequest = "focus on **difficult and complex questions**, as the student is generally strong in ${subject}.";
            } else { // moderate
                difficultyRequest = "a mix of foundational concepts and moderately complex application problems.";
            }

        } else if (performance_summary?.overall_accuracy) {
            // RULE 3: No topic or subject data, use overall performance
            const overallAccuracy = getNum(performance_summary.overall_accuracy);
            const overallAccuracyPercent = (overallAccuracy * 100).toFixed(0);
            
            performanceProfile = `No topic or subject data. Using **overall performance: ${overallAccuracyPercent}% accuracy**.`;

            if (overallAccuracy < 0.6) { // Weaker student
                difficultyRequest = "focus on **common topics for board exams** and provide **better, more detailed explanations** in the answers. The student has a weaker overall performance.";
            } else if (overallAccuracy > 0.8) { // Stronger student
                difficultyRequest = "focus on **complex, lesser-known facts, and advanced application questions**. The student has a strong overall performance.";
            } else { // Moderate student
                difficultyRequest = "a standard mix of foundational concepts and common application problems. The student has a moderate overall performance.";
            }
        }
        // RULE 4 (Default): If no data exists at all, the default values are used.

    } catch (e) {
        console.warn("Could not build performance profile:", e.message);
        // Errors in this block are non-fatal; we'll just use the default profile.
    }

    // --- 3. GENERATION ---
    // Inject the retrieved context into the prompt
    const prompt = `
    You are an expert academic tutor for Indian students. Your task is to generate high-quality, personalized flashcards.

    **Constraints & Rules:**
    1.  **Source:** All information MUST be derived *exclusively* from the NCERT textbook.
    2.  **Audience:** Class ${userClass} (PCM Stream).
    3.  **Format:** You MUST output *only* a valid JSON object.
    4.  **Personalization:** You MUST tailor the flashcards based on the student's performance.

    **Input:**
    * **Class:** ${userClass}
    * **Subject:** ${subject}
    * **Topic:** ${topic}

    **--- 💡 STUDENT PERFORMANCE PROFILE (RAG) 💡 ---**
    * **Profile:** ${performanceProfile}
    * **Action:** Based on this profile, ${difficultyRequest}.
    **--- -------------------------------------- ---**

    **Required JSON Output Structure:**
    {
      "flashcards": [
        {
          "front": "<Question, Term, or 'Define: ...'>",
          "back": "<Concise, NCERT-based answer or definition>"
        },
        {
          "front": "<Another question or formula name...>",
          "back": "<The corresponding answer or formula...>"
        }
      ]
    }

    Generate 10-15 flashcards for the topic: "${topic}" from the ${subject} NCERT textbook.
    `;
    // --- 🔸 END OF PROMPT 🔸 ---

    console.log(`Generating flashcards for Class ${userClass}, ${subject}, ${topic}...`);
    console.log(`Using profile: ${performanceProfile}`); // Log the profile for debugging
    
    const response = await callRAGModel(prompt);
    
    // Add context to the response before sending it back
    return {
        subject,
        topic,
        class: userClass,
        _debug_RAG_profile: performanceProfile, // Send profile to client for debugging
        ...response // This will include the "flashcards": [...] array
    };
}

