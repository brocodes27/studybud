// --- ⬇️ API ENDPOINT FOR FLASHCARDS ⬇️ ---
app.post('/generate-flashcards', async (req, res) => {
    try {
        const auth_user_id = req.headers.authorization?.split(' ')[1];
        if (!auth_user_id) {
            return res.status(401).json({ error: 'Authorization required' });
        }

        // Pass the request body which should contain { "subject": "...", "topic": "..." }
        const flashcardData = await generateFlashcards(auth_user_id, req.body);
        
        res.json(flashcardData); // Send the parsed JSON object

    } catch (error) {
        console.error('❌ Error in /generate-flashcards:', error.message);
        // Differentiate between user error (e.g., bad input) and server error
        if (error.message.includes("Missing")) {
            res.status(400).json({ error: error.message }); // 400 Bad Request
        } else {
            res.status(500).json({ error: error.message }); // 500 Internal Server Error
        }
    }
});
