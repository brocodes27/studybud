// ✅ Fixed Gemini API call
async function callRAGModel(prompt) {
    const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
    if (!GEMINI_API_KEY) throw new Error("Missing GEMINI_API_KEY in environment");

    // Using v1 and gemini-1.5-flash
    const API_URL = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${GEMINI_API_KEY}`;

    // Using snake_case ("response_mime_type") as required by the v1 API
    const requestBody = {
        contents: [{
            parts: [{ text: prompt }]
        }],
        generationConfig: {
            response_mime_type: "application/json", // Request JSON output
        }
    };

    const response = await fetch(API_URL, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify(requestBody)
    });

    const data = await response.json();

    if (!response.ok) {
        console.error("Gemini API error:", data);
        const errorDetails = data.error?.message || response.statusText;
        throw new Error(`Failed to call Gemini API: ${errorDetails}`);
    }
    
    // ✅ Extract model output correctly (it should be a JSON string)
    const generatedText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    
    if (!generatedText) {
        // Check if the response was blocked
        if (data.candidates?.[0]?.finishReason === 'SAFETY') {
            throw new Error("Model response blocked due to safety settings.");
        }
        throw new Error("No response text generated by the model.");
    }
    
    // Parse the JSON string from the model
    try {
        const jsonData = JSON.parse(generatedText);
        return jsonData; // Return the parsed JSON object
    } catch (parseError) {
        console.error("Failed to parse JSON response from model:", generatedText);
        throw new Error("Model did not return valid JSON.");
    }
}


